parse_args() {
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --home | --bin-dir | --from-source | --backup-file | --model-dir | --small-port | --large-port | --extension-port | --extension-id)
        [[ $# -ge 2 && -n "$2" ]] || fail "$1 needs a value"
        case "$1" in
          --home) MORDRED_HOME="$2" ;;
          --bin-dir) BIN_DIR="$2" ;;
          --from-source) SOURCE_DIR="$2" ;;
          --backup-file) BACKUP_FILE="$2" ;;
          --model-dir) MODEL_DIR="$2" ;;
          --small-port) SMALL_PORT="$2"; PORTS_GIVEN+=(SMALL_PORT) ;;
          --large-port) LARGE_PORT="$2"; PORTS_GIVEN+=(LARGE_PORT) ;;
          --extension-port) EXTENSION_PORT="$2"; PORTS_GIVEN+=(EXTENSION_PORT) ;;
          --extension-id) EXTENSION_IDS+=(--extension-id "$2") ;;
        esac
        shift 2
        ;;
      --with-telegram) EXTRA_ARGS+=(--with-telegram); shift ;;
      --large-model) LARGE_MODEL="yes"; shift ;;
      --no-large-model) LARGE_MODEL="no"; shift ;;
      --no-services) SERVICES=0; shift ;;
      --no-setup) RUN_SETUP=0; shift ;;
      --unattended-keys) KEY_ARGS=(--unattended-keys); shift ;;
      --dialogs) DIALOGS=1; shift ;;
      -h | --help) usage; exit 0 ;;
      *) fail "unknown option: $1 (see --help)" ;;
    esac
  done
  local port
  for port in "$SMALL_PORT" "$LARGE_PORT" "$EXTENSION_PORT"; do
    [[ "$port" =~ ^[0-9]+$ ]] || fail "ports must be numbers"
  done
  [[ "$SMALL_PORT" != "$LARGE_PORT" ]] || fail "the two model servers need different ports"
  [[ "$EXTENSION_PORT" != "$SMALL_PORT" && "$EXTENSION_PORT" != "$LARGE_PORT" ]] \
    || fail "the extension server needs a port of its own"
}

absolute_path() {
  # The folder need not exist yet: resolve its parent.
  local path="$1"
  case "$path" in
    \~) path="$HOME" ;;
    \~/*) path="$HOME/${path#\~/}" ;;
  esac
  local parent base
  parent="$(dirname "$path")"
  base="$(basename "$path")"
  mkdir -p "$parent"
  printf '%s/%s\n' "$(cd "$parent" && pwd -P)" "$base"
}

check_host() {
  [[ "$(uname -s)" == "Darwin" ]] || fail "this installer is for macOS for now (Bonsai runs on MLX)"
  [[ "$(uname -m)" == "arm64" ]] || fail "Bonsai needs an Apple silicon Mac (arm64)"
  local tool
  for tool in curl git; do
    command -v "$tool" >/dev/null 2>&1 && continue
    if [[ "$DIALOGS" == 1 ]]; then
      # Apple's own window offers to install them; nothing is typed.
      xcode-select --install >/dev/null 2>&1 || true
      fail "$(msg installer.needsTools "Mordred needs Apple's Command Line Tools. Install them in the window that just opened, then open the Mordred installer again.")"
    fi
    fail "$tool is required (install the Xcode Command Line Tools: xcode-select --install)"
  done
  if [[ -n "$SOURCE_DIR" ]]; then
    [[ -f "$SOURCE_DIR/pyproject.toml" && -f "$SOURCE_DIR/scripts/install.sh" ]] \
      || fail "--from-source: $SOURCE_DIR is not a hermes-mordred checkout"
  fi
}

# A file of this repository: from the checkout, or downloaded from MORDRED_REF.
repo_file() {
  local name="$1" dest="$2"
  if [[ -n "$SOURCE_DIR" ]]; then
    cp "$SOURCE_DIR/$name" "$dest"
  else
    curl -fsSL "https://raw.githubusercontent.com/${MORDRED_REPO}/${MORDRED_REF}/${name}" -o "$dest" \
      || fail "could not download $name"
  fi
}

# Every command below runs against this folder only.
use_home() {
  export HERMES_HOME="$MORDRED_HOME"
  export MORDRED_SEKEY_HELPER="$MORDRED_HOME/bin/mordred-hermes-sekey"
  export PATH="$MORDRED_HOME/hermes-agent/.hermes/bin:$PATH"
  # A key of another home must never reach this one.
  unset HERMES_MEMORY_KEY
}

install_hermes() {
  local checkout="$MORDRED_HOME/hermes-agent"
  if [[ -d "$checkout/.git" ]] && [[ "$(git -C "$checkout" rev-parse HEAD 2>/dev/null)" == "$HERMES_AGENT_COMMIT" ]] \
    && [[ -x "$checkout/.hermes/bin/hermes" ]]; then
    info "Hermes Agent ${HERMES_AGENT_COMMIT:0:8} is already installed in $MORDRED_HOME"
    return
  fi
  say "Installing Hermes Agent ${HERMES_AGENT_COMMIT:0:8} into $MORDRED_HOME"
  mkdir -p "$MORDRED_HOME"
  chmod 700 "$MORDRED_HOME"
  if [[ ! -e "$MORDRED_HOME/config.yaml" ]]; then
    # Keep this copy's commands off the shared PATH: other Hermes installs own `hermes`.
    printf '%s\ncli:\n  expose_on_path: false\n' \
      "# Mordred's own Hermes (hermes-agent ${HERMES_AGENT_COMMIT:0:8}); its commands stay off the shared PATH." \
      >"$MORDRED_HOME/config.yaml"
    chmod 600 "$MORDRED_HOME/config.yaml"
  fi
  local installer="$WORK_DIR/hermes-install.sh"
  curl -fsSL "https://raw.githubusercontent.com/${HERMES_AGENT_REPO}/${HERMES_AGENT_COMMIT}/scripts/install.sh" \
    -o "$installer" || fail "could not download the Hermes Agent installer"
  bash "$installer" --commit "$HERMES_AGENT_COMMIT" --hermes-home "$MORDRED_HOME" --dir "$checkout" --non-interactive
  [[ -x "$checkout/.hermes/bin/hermes" ]] || fail "Hermes Agent did not install its launcher"
}

install_mordred() {
  say "Installing hermes-mordred"
  local args=("${EXTRA_ARGS[@]}")
  local installer="$WORK_DIR/mordred-install.sh"
  if [[ -n "$SOURCE_DIR" ]]; then
    args+=(--from-source "$SOURCE_DIR")
  fi
  repo_file scripts/install.sh "$installer"
  bash "$installer" "${args[@]}"
}

install_helper() {
  if [[ -x "$MORDRED_SEKEY_HELPER" ]]; then
    # A helper with multi-key presence sessions lets setup and start-up confirm once.
    if printf '{"cmd":"capabilities"}' | "$MORDRED_SEKEY_HELPER" 2>/dev/null | grep -q '"presence_stores"'; then
      info "the Secure Enclave helper is already built"
      return
    fi
    # The vault's keychain records trust only the helper that wrote them: a
    # rebuilt one would make macOS ask for the login password for each of them.
    if [[ -e "$MORDRED_HOME/mordred/vault" ]]; then
      info "keeping the existing Secure Enclave helper (this vault's keychain records trust it)"
      return
    fi
  fi
  say "Building the Secure Enclave helper (this can take a few minutes)"
  hermes-mordred keyvault enable-se --install-dir "$MORDRED_HOME/bin"
}

write_wrapper() {
  local name="$1" target="$2" body="$3" path="$BIN_DIR/$1"
  if [[ -e "$path" ]] && ! grep -qF "$WRAPPER_MARKER" "$path"; then
    fail "$(msg installer.fileInTheWay "{path} is in the way and was not made by Mordred. Move it elsewhere, then open the Mordred installer again." path "$path")"
  fi
  mkdir -p "$BIN_DIR"
  cat >"$path" <<EOF
#!/bin/sh
$WRAPPER_MARKER
# $name: $target in $MORDRED_HOME, never ~/.hermes.
HERMES_HOME="$MORDRED_HOME"
MORDRED_SEKEY_HELPER="$MORDRED_HOME/bin/mordred-hermes-sekey"
PATH="$MORDRED_HOME/hermes-agent/.hermes/bin:\$PATH"
export HERMES_HOME MORDRED_SEKEY_HELPER PATH
unset HERMES_MEMORY_KEY
$body
exec "$MORDRED_HOME/hermes-agent/.hermes/bin/$target" "\$@"
EOF
  chmod 755 "$path"
}

install_wrappers() {
  say "Adding mordred-hermes and hermes-mordred to $BIN_DIR"
  write_wrapper mordred-hermes hermes "if [ \"\${1:-}\" = update ]; then
  echo 'mordred-hermes: this Hermes is pinned for Mordred (hermes-agent ${HERMES_AGENT_COMMIT:0:8}); update it by running the Mordred installer again.' >&2
  exit 1
fi"
  write_wrapper hermes-mordred hermes-mordred ""
  case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *) info "note: $BIN_DIR is not on your PATH; add it to use the two commands by name" ;;
  esac
}

install_runtime() {
  local venv="$MORDRED_HOME/models/runtime"
  local uv
  uv="$(find "$MORDRED_HOME/tools" -maxdepth 2 -type f -name uv -perm -u+x 2>/dev/null | head -1)"
  [[ -n "$uv" ]] || uv="$(command -v uv || true)"
  [[ -n "$uv" ]] || fail "uv was not found (Hermes Agent's installer normally provides it)"
  say "Installing the model server's Python packages"
  local requirements="$WORK_DIR/bonsai-runtime.txt"
  repo_file "$RUNTIME_REQUIREMENTS" "$requirements"
  mkdir -p "$MORDRED_HOME/models"
  [[ -x "$venv/bin/python" ]] || "$uv" venv -q -p 3.12 "$venv"
  "$uv" pip install -q -p "$venv/bin/python" -r "$requirements"
}

# The revision an `hf download --local-dir` folder holds, from its download record.
model_revision() {
  local record="$1/.cache/huggingface/download/config.json.metadata"
  [[ -f "$record" ]] && head -n 1 "$record"
}

# A model in --model-dir, if there is one.
existing_model() {
  [[ -n "$MODEL_DIR" && -d "$MODEL_DIR/${1#*/}" ]]
}

# Where a model lives: its copy in --model-dir when there is one, else the home.
# Never a link inside the home: the database-encryption inventory refuses a home
# with links it cannot follow, so the settings name the real folder instead.
model_path() {
  if existing_model "$1"; then
    printf '%s/%s\n' "$MODEL_DIR" "${1#*/}"
  else
    printf '%s/models/%s\n' "$MORDRED_HOME" "${1#*/}"
  fi
}

# Check an existing copy before using it in place of a download.
use_existing_model() {
  local repo="$1" revision="$2" src in_home="$MORDRED_HOME/models/${1#*/}"
  src="$(model_path "$repo")"
  [[ -f "$src/config.json" && -f "$src/model.safetensors" ]] || fail "$src is not a complete copy of $repo"
  [[ "$(model_revision "$src" || true)" == "$revision" ]] \
    || fail "$src is not revision ${revision:0:12} of $repo; update it, or leave out --model-dir to download"
  case "$src/" in
    "$HOME/Documents/"* | "$HOME/Desktop/"* | "$HOME/Downloads/"* | "$HOME/Library/Mobile Documents/"*)
      fail "$src is in a folder macOS keeps from login services; move it out of ~/Documents, ~/Desktop, ~/Downloads and iCloud Drive"
      ;;
  esac
  if [[ -L "$in_home" ]]; then
    rm "$in_home"  # an earlier installer linked it here
  elif [[ -e "$in_home" ]]; then
    info "a downloaded copy is also in $in_home; it is no longer used and can be deleted"
  fi
}

# Download a model, reporting how far it got: the Mac installer itself shows
# only "Running package scripts" for the whole download.
download_model() {
  local repo="$1" revision="$2" size_mb="$3" dest="$MORDRED_HOME/models/${1#*/}"
  local name="${1#*/}" pid status=0 done_mb percent reported=0 last_print=0
  if existing_model "$repo"; then
    say "Using $repo from $MODEL_DIR (no download)"
    use_existing_model "$repo" "$revision"
    return
  fi
  say "Downloading $repo (about ${size_mb} MB)"
  notify "$(msg installer.downloadStarted "Downloading {name} (about {size} MB). The installer keeps going on its own." name "$name" size "$size_mb")"
  mkdir -p "$dest"
  HF_HUB_DISABLE_TELEMETRY=1 "$MORDRED_HOME/models/runtime/bin/hf" download "$repo" \
    --revision "$revision" --local-dir "$dest" >/dev/null 2>&1 &
  pid=$!
  while kill -0 "$pid" 2>/dev/null; do
    sleep 2
    done_mb=$(($(du -sk "$dest" 2>/dev/null | awk '{ print $1 }') / 1024))
    percent=$((done_mb * 100 / size_mb))
    ((percent > 99)) && percent=99
    if ((SECONDS - last_print >= 10)); then
      info "downloaded ${done_mb} of about ${size_mb} MB (${percent}%)"
      last_print=$SECONDS
    fi
    if ((percent / 25 > reported)); then
      reported=$((percent / 25))
      notify "$(msg installer.downloadProgress "Downloading {name}: {percent}% done." name "$name" percent "$percent")"
    fi
  done
  wait "$pid" || status=$?
  ((status == 0)) || info "the download of $repo exited with status $status"
  ((status == 0)) || fail "$(msg installer.downloadFailed "{name} did not download. Check the network, then open the Mordred installer again: it continues where it stopped." name "$name")"
  [[ -f "$dest/config.json" ]] || fail "$(msg installer.downloadFailed "{name} did not download. Check the network, then open the Mordred installer again: it continues where it stopped." name "$name")"
  info "downloaded $repo"
}

want_large_model() {
  case "$LARGE_MODEL" in
    yes) return 0 ;;
    no) return 1 ;;
  esac
  # Nothing to download: it is already here, or in --model-dir.
  [[ -d "$(model_path "$LARGE_MODEL_REPO")" ]] && return 0
  if [[ "$DIALOGS" == 1 ]]; then
    local download
    download="$(msg button.download "Download")"
    [[ "$(dialog "$(msg installer.largeModel "Also download the large model (Bonsai 27B, about 8 GB)? It writes headlines and topics for your history. You can add it later by opening the Mordred installer again.")" "$(msg button.notNow "Not now")" "$download")" == "$download" ]]
    return
  fi
  if [[ ! -t 0 ]]; then
    info "skipping the large model (8 GB); run again with --large-model to add it"
    return 1
  fi
  local answer
  printf '\nThe large model (Bonsai 27B, about 8 GB) writes headlines and topics.\n'
  read -r -p "Download it now? [y/N] " answer
  [[ "$answer" == [yY]* ]]
}

configure_models() {
  local small large
  small="$(model_path "$SMALL_MODEL_REPO")"
  large="$(model_path "$LARGE_MODEL_REPO")"
  local python="$MORDRED_HOME/models/runtime/bin/python"
  say "Pointing Hermes and Mordred at the local models"
  # Hermes's own chat model: the small one.
  hermes config set model.provider custom >/dev/null
  hermes config set model.base_url "http://127.0.0.1:${SMALL_PORT}/v1" >/dev/null
  hermes config set model.default "$small" >/dev/null
  hermes config set MORDRED_RECALL_AGENT_ENDPOINT "http://127.0.0.1:${SMALL_PORT}/v1" >/dev/null
  hermes config set MORDRED_RECALL_AGENT_MODEL "$small" >/dev/null
  if [[ -d "$large" ]]; then
    hermes config set MORDRED_RECALL_LLM_ENDPOINT "http://127.0.0.1:${LARGE_PORT}/v1" >/dev/null
    hermes config set MORDRED_RECALL_LLM_MODEL "$large" >/dev/null
    # Hermes starts the large model only while it has work, and stops it when idle.
    local command
    # Split like a shell would (shlex) when Hermes runs it: quote the paths.
    printf -v command '%q -m mlx_vlm.server --model %q --host 127.0.0.1 --port %s --enable-thinking' \
      "$python" "$large" "$LARGE_PORT"
    hermes config set MORDRED_RECALL_LLM_COMMAND "$command" >/dev/null
  fi
}

# The answers `hermes-mordred setup` would otherwise ask for, with the defaults
# it offers, except that the local model is the small Bonsai one. Change them
# later with `hermes-mordred configure` / `hermes-mordred network init`.
configure_mordred() {
  local small
  small="$(model_path "$SMALL_MODEL_REPO")"
  say "Writing Mordred's policy (local model only, direct network)"
  hermes-mordred configure --non-interactive --no-allow-cloud-llm \
    --local-llm-endpoint "http://127.0.0.1:${SMALL_PORT}/v1" --local-llm-model-id "$small" \
    --cloud-attempt-action always-block --harness none
  hermes-mordred network init --non-interactive --path clearnet
}

# The pid launchd runs for this login-session label, if any.
agent_pid() {
  { launchctl print "gui/$(id -u)/$1" 2>/dev/null || true; } | awk '$1 == "pid" && $2 == "=" { print $3; exit }'
}

# The label `hermes-mordred extension agent` gives this home (launch_agent.label_for).
extension_agent_label() {
  local resolved="$MORDRED_HOME"
  if [[ -d "$MORDRED_HOME" ]]; then
    resolved="$(cd "$MORDRED_HOME" && pwd -P)"
  fi
  printf 'com.mordred.hermes.extension.%s\n' "$(printf '%s' "$resolved" | shasum -a 256 | cut -c1-8)"
}

# The pid of a program other than this home's own login agent listening on a port
# (empty when the port is free or ours): a second server could not bind it.
foreign_listener() {
  local port="$1" label="$2" listener own=""
  listener="$(lsof -nP -t -iTCP:"$port" -sTCP:LISTEN 2>/dev/null | head -n 1 || true)"
  [[ -n "$listener" ]] || return 0
  [[ -z "$label" ]] || own="$(agent_pid "$label")"
  [[ -n "$own" && "$own" == "$listener" ]] || printf '%s\n' "$listener"
}

# Keep each server's port, or move a default one another program took to a free
# one nearby. A port given on the command line is never moved.
pick_port() {
  local var="$1" label="$2" what="$3" port listener candidate
  port="${!var}"
  listener="$(foreign_listener "$port" "$label")"
  [[ -n "$listener" ]] || return 0
  if [[ " ${PORTS_GIVEN[*]-} " == *" $var "* ]]; then
    fail "port $port ($what) is in use by another program (pid $listener); stop it, or pick another port with the matching --*-port option"
  fi
  for ((candidate = 47714; candidate < 47800; candidate++)); do
    [[ "$candidate" != "$SMALL_PORT" && "$candidate" != "$LARGE_PORT" && "$candidate" != "$EXTENSION_PORT" ]] || continue
    [[ -z "$(foreign_listener "$candidate" "")" ]] || continue
    info "port $port ($what) is in use by another program (pid $listener); using $candidate instead"
    printf -v "$var" '%s' "$candidate"
    return 0
  done
  fail "no free port for the $what between 47714 and 47799"
}

check_ports() {
  [[ "$SERVICES" == 1 ]] || return 0
  pick_port SMALL_PORT "$(model_agent_label)" "small model server"
  pick_port LARGE_PORT "" "large model server"
  pick_port EXTENSION_PORT "$(extension_agent_label)" "extension server"
}

# One label per home, like `hermes-mordred extension agent`: two homes never replace each other's agent.
model_agent_label() {
  local hash
  hash="$(printf '%s' "$MORDRED_HOME" | shasum -a 256 | cut -c1-10)"
  printf 'com.mordred.hermes.model-small.%s\n' "$hash"
}

install_small_model_agent() {
  local label plist small python log
  label="$(model_agent_label)"
  plist="$HOME/Library/LaunchAgents/$label.plist"
  small="$(model_path "$SMALL_MODEL_REPO")"
  python="$MORDRED_HOME/models/runtime/bin/python"
  log="$MORDRED_HOME/logs/model-small.log"
  say "Starting the small model at login ($label)"
  mkdir -p "$HOME/Library/LaunchAgents" "$MORDRED_HOME/logs"
  cat >"$plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>$label</string>
  <key>ProgramArguments</key>
  <array>
    <string>$python</string><string>-m</string><string>mlx_vlm.server</string>
    <string>--model</string><string>$small</string>
    <string>--host</string><string>127.0.0.1</string>
    <string>--port</string><string>$SMALL_PORT</string>
    <string>--enable-thinking</string>
  </array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict>
  <key>ThrottleInterval</key><integer>30</integer>
  <key>StandardOutPath</key><string>$log</string>
  <key>StandardErrorPath</key><string>$log</string>
</dict>
</plist>
EOF
  unload_agent "$label"
  launchctl bootstrap "gui/$(id -u)" "$plist"
}

# `launchctl bootout` returns before the job is gone, and bootstrapping the same
# label meanwhile fails with error 5: wait (up to 15 seconds) until it is gone.
unload_agent() {
  local label="$1" tries=0
  launchctl bootout "gui/$(id -u)/$label" >/dev/null 2>&1 || true
  while launchctl print "gui/$(id -u)/$label" >/dev/null 2>&1; do
    ((tries += 1))
    ((tries <= 30)) || fail "$(msg installer.serverDidNotStop "Mordred's server did not stop. Wait a minute, then open the Mordred installer again.")"
    sleep 0.5
  done
}

# On a re-run this home's own extension server would hold the databases open, and
# setup's encryption steps refuse while a Hermes process runs: stop it first.
# Prints 1 when it was running.
stop_own_extension_agent() {
  local label
  label="$(extension_agent_label)"
  if [[ -n "$(agent_pid "$label")" ]]; then
    unload_agent "$label"
    printf '1\n'
  fi
}

# Setup's encryption steps need the home to themselves; name whatever still holds it
# (often a `hermes` or `hermes setup` left open in another terminal, or a setup
# an interrupted install left behind). The Mac installer offers to stop them.
require_home_unused() {
  local lock="$MORDRED_HOME/mordred/db-encryption.lock" holders pid tries
  [[ -e "$lock" ]] || return 0
  holders="$(lsof -t "$lock" 2>/dev/null | sort -u || true)"
  [[ -n "$holders" ]] || return 0
  for pid in $holders; do
    info "still running in this Mordred home: pid $pid ($(ps -o comm= -p "$pid" 2>/dev/null || echo '?'))"
  done
  if [[ "$DIALOGS" != 1 ]]; then
    fail "quit those (Ctrl+C in their terminal, or quit Hermes), then run the installer again"
  fi
  local stop
  stop="$(msg button.stopAndContinue "Stop and Continue")"
  [[ "$(dialog "$(msg installer.stillRunning "Mordred is still running (an earlier install, or a Hermes window). Stop it and continue?")" "$(msg button.cancel "Cancel")" "$stop")" == "$stop" ]] ||
    fail "$(msg installer.closeAndRetry "Mordred is still running. Close it, then open the Mordred installer again.")"
  # shellcheck disable=SC2086 # one pid per word
  kill -TERM $holders 2>/dev/null || true
  for ((tries = 0; tries < 20; tries++)); do
    [[ -n "$(lsof -t "$lock" 2>/dev/null || true)" ]] || return 0
    sleep 0.5
  done
  # shellcheck disable=SC2086
  kill -KILL $holders 2>/dev/null || true
  sleep 1
  [[ -z "$(lsof -t "$lock" 2>/dev/null || true)" ]] || fail "$(msg installer.couldNotStop "Mordred could not be stopped. Restart the Mac, then open the Mordred installer again.")"
}

# A setup stopped after it made the keys and before it saved their backup file
# leaves keys nobody could restore on another Mac (the backup's passphrase was
# only in that file). Nothing was encrypted with them yet: the vault, memory and
# databases come after the backup. Start the keys over instead of keeping them.
restart_unbacked_keys() {
  [[ -f "$MORDRED_HOME/mordred/keyvault/meta.json" ]] || return 0
  [[ ! -e "$BACKUP_FILE" && ! -e "$MORDRED_HOME/mordred/vault" ]] || return 0
  info "an earlier setup stopped before it saved the backup file; starting the keys over (nothing was encrypted with them)"
  hermes-mordred keyvault reset --yes || fail "$(msg installer.unfinishedKeys "The keys of an earlier, unfinished setup could not be removed. Open the Mordred installer again.")"
}

# Where this home's backup file is: the path is remembered, so a later run (and
# the passphrase setup reads back from the file) finds the same one.
resolve_backup_file() {
  local remembered="$MORDRED_HOME/mordred/backup-file-location"
  if [[ -z "$BACKUP_FILE" && -f "$remembered" ]]; then
    BACKUP_FILE="$(head -n 1 "$remembered")"
  fi
  if [[ -z "$BACKUP_FILE" ]]; then
    BACKUP_FILE="$HOME/Downloads/mordred-keyvault-backup.mrkv"
  fi
  BACKUP_FILE="$(absolute_path "$BACKUP_FILE")"
  mkdir -p "$MORDRED_HOME/mordred"
  printf '%s\n' "$BACKUP_FILE" >"$remembered"
}

run_setup() {
  resolve_backup_file
  require_home_unused
  restart_unbacked_keys
  # Nothing is asked in the terminal: the passphrase is generated and saved in the
  # backup file, and the keys confirm with Touch ID dialogs (unless --unattended-keys).
  # One Touch ID covers the whole step: `--no-prompts` holds one presence
  # window over the keys, the vault, memory and the databases (imports need them
  # encrypted). Nothing of this home runs yet (the login services start after
  # this), so the conversion never waits for a running Hermes.
  if [[ "${KEY_ARGS[*]-}" == *--unattended-keys* ]]; then
    say "Setting up Mordred's keys and encryption"
  else
    say "Setting up Mordred's keys and encryption (confirm once with Touch ID)"
  fi
  local attempt status
  for attempt in 1 2 3; do
    if [[ "$DIALOGS" == 1 && "${KEY_ARGS[*]-}" != *--unattended-keys* ]]; then
      # The Touch ID window opens on its own while the installer is in front;
      # a dialog first makes sure someone is looking when it does.
      dialog "$(msg installer.touchIdNext "Next, confirm with Touch ID: once now to set up Mordred's keys, and once more in a moment when Mordred starts. Press OK, then touch the sensor when the Touch ID window appears.")" "$(msg button.ok "OK")" >/dev/null
    fi
    status=0
    hermes-mordred setup --skip-hermes-setup --no-prompts --backup-file "$BACKUP_FILE" ${KEY_ARGS[@]+"${KEY_ARGS[@]}"} || status=$?
    # 75: the first Touch ID was missed or cancelled, before anything was set up.
    [[ "$status" == 75 ]] || return "$status"
    local retry not_confirmed
    not_confirmed="$(msg installer.touchIdNotConfirmed "Touch ID was not confirmed, so the keys were not set up. Open the Mordred installer again.")"
    if [[ "$DIALOGS" != 1 || "$attempt" == 3 ]]; then
      fail "$not_confirmed"
    fi
    retry="$(msg button.tryAgain "Try Again")"
    [[ "$(dialog "$(msg installer.touchIdRetry "Touch ID was not confirmed, so nothing was set up yet. Try again?")" "$(msg button.cancel "Cancel")" "$retry")" == "$retry" ]] ||
      fail "$not_confirmed"
  done
}

# The Mac installer shows only "the installation failed" when a step stops the
# script without its own message: say so in a dialog that opens the log.
unexpected_failure() {
  trap - ERR
  fail "$(msg installer.unexpected "A step stopped unexpectedly (line {line}). Open the log to see which; then open the Mordred installer again: it continues where it stopped." line "$1")"
}

main() {
  parse_args "$@"
  if [[ "$DIALOGS" == 1 ]]; then
    set -E
    trap 'unexpected_failure "$LINENO"' ERR
  fi
  check_host
  MORDRED_HOME="$(absolute_path "$MORDRED_HOME")"
  BIN_DIR="$(absolute_path "$BIN_DIR")"
  [[ "$MORDRED_HOME" != "$HOME/.hermes" ]] || fail "--home must not be ~/.hermes: that folder belongs to your other Hermes"
  if [[ -n "$SOURCE_DIR" ]]; then
    SOURCE_DIR="$(absolute_path "$SOURCE_DIR")"
  fi
  if [[ -z "$MODEL_DIR" && -d "$DEFAULT_MODEL_DIR" ]]; then
    MODEL_DIR="$DEFAULT_MODEL_DIR"  # models fetched by hand earlier: never download a second copy
  fi
  if [[ -n "$MODEL_DIR" ]]; then
    [[ -d "$MODEL_DIR" ]] || fail "--model-dir: $MODEL_DIR is not a folder"
    MODEL_DIR="$(cd "$MODEL_DIR" && pwd -P)"
  fi
  WORK_DIR="$(mktemp -d)"
  trap 'rm -rf "$WORK_DIR"' EXIT
  use_home
  check_ports

  install_hermes
  install_mordred
  install_helper
  install_wrappers
  install_runtime
  download_model "$SMALL_MODEL_REPO" "$SMALL_MODEL_REVISION" 1100
  if want_large_model; then
    download_model "$LARGE_MODEL_REPO" "$LARGE_MODEL_REVISION" 8200
  fi
  configure_models
  configure_mordred
  if [[ "$RUN_SETUP" == 1 ]]; then
    local was_running
    was_running="$(stop_own_extension_agent)"
    [[ -z "$was_running" ]] || info "stopped this home's extension server for the setup"
    run_setup
    if [[ -n "$was_running" && "$SERVICES" != 1 ]]; then
      launchctl bootstrap "gui/$(id -u)" "$HOME/Library/LaunchAgents/$(extension_agent_label).plist" || true
    fi
  fi
  if [[ "$SERVICES" == 1 ]]; then
    install_small_model_agent
    say "Starting the extension server at login"
    hermes-mordred extension agent install --port "$EXTENSION_PORT"
    say "Letting the Mordred extension find this Mac"
    hermes-mordred extension browsers install ${EXTENSION_IDS[@]+"${EXTENSION_IDS[@]}"}
  fi

  say "Done"
  if [[ "$DIALOGS" == 1 && "$RUN_SETUP" == 1 ]]; then
    dialog "$(msg installer.done "Mordred is installed and starts when you log in. Its backup file is {path}: that file alone restores your keys on another Mac, so keep a copy somewhere safe and private." path "$BACKUP_FILE")" "$(msg button.ok "OK")" >/dev/null
  fi
  info "Mordred lives in $MORDRED_HOME. Commands: mordred-hermes (Hermes), hermes-mordred (Mordred)."
  info "Check it with: hermes-mordred status"
}

main "$@"
