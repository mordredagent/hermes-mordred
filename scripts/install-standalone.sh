#!/usr/bin/env bash
# Install Mordred with its own Hermes, its own local AI (Bonsai), and set it up.
#
# Everything lives in one folder (default ~/.mordred-hermes) that no other
# Hermes uses: a Hermes Agent pinned to a commit Mordred is tested with, the
# hermes-mordred plugin, the Secure Enclave helper, the Bonsai models and the
# Python packages that serve them. ~/.hermes, Hermes Desktop and any `hermes`
# on PATH are left alone, and `hermes update` is refused for this copy, so a
# Hermes release Mordred does not support yet cannot break it.
#
# Two commands are added to ~/.local/bin:
#   mordred-hermes   Hermes itself, in this folder (chat, `setup model`, ...)
#   hermes-mordred   Mordred's commands, in this folder (status, imports, ...)
#
# macOS on Apple silicon only for now: Bonsai runs on MLX.

set -euo pipefail

