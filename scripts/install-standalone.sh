say() { printf '\n==> %s\n' "$*"; }
info() { printf 'mordred: %s\n' "$*"; }
# The Mac's language for what the user reads (dialogs, notifications): the first
# of macOS's preferred languages that Mordred has words for, else English.
ui_language() {
  local first base
  first="$(defaults read -g AppleLanguages 2>/dev/null | sed -n 's/^[[:space:]]*"\{0,1\}\([A-Za-z-]*\)"\{0,1\},\{0,1\}$/\1/p' | head -n 1)"
  case "$first" in
    zh-Hans* | zh-CN* | zh-SG*) printf 'zhCN' ;;
    zh-Hant* | zh-TW* | zh-HK* | zh-MO*) printf 'zhTW' ;;
    *)
      base="${first%%-*}"
      case "$base" in
        ja | ko | vi | th | id | ms | es | pt | fr | de | it | nl | sv | pl | ru | uk | tr | ar | he | fa | hi | bn) printf '%s' "$base" ;;
        *) printf 'en' ;;
      esac
      ;;
  esac
}

# Translations sit next to Mordred's code (src/mordred_hermes/i18n/strings/<lang>.json).
strings_dir() {
  local here
  if [[ -n "$SOURCE_DIR" && -d "$SOURCE_DIR/src/mordred_hermes/i18n/strings" ]]; then
    printf '%s' "$SOURCE_DIR/src/mordred_hermes/i18n/strings"
    return
  fi
  here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." 2>/dev/null && pwd -P)" || return 0
  [[ ! -d "$here/src/mordred_hermes/i18n/strings" ]] || printf '%s' "$here/src/mordred_hermes/i18n/strings"
}

# msg KEY "English text with {name}" [name value]...: the text in the Mac's
# language when Mordred has it, else the English given here; then {name}s filled in.
UI_LANGUAGE=""
msg() {
  local key="$1" text="$2" dir file translated name value
  shift 2
  [[ -n "$UI_LANGUAGE" ]] || UI_LANGUAGE="$(ui_language)"
  dir="$(strings_dir)"
  file="$dir/$UI_LANGUAGE.json"
  if [[ "$UI_LANGUAGE" != en && -n "$dir" && -f "$file" ]]; then
    translated="$(plutil -extract "$key" raw -o - "$file" 2>/dev/null || true)"
    [[ -z "$translated" ]] || text="$translated"
  fi
  while [[ $# -ge 2 ]]; do
    name="$1" value="$2"
    shift 2
    text="${text//\{$name\}/$value}"
  done
  printf '%s' "$text"
}

fail() {
  printf 'mordred: error: %s\n' "$*" >&2
  if [[ "$DIALOGS" == 1 ]]; then
    # The Mac installer itself shows only "the installation failed": this
    # dialog says why, and opens the full log (postinstall names it).
    local answer text show ok
    text="$(msg installer.failed "Mordred could not be installed: {reason}" reason "$*")"
    show="$(msg button.showLog "Show Log")"
    ok="$(msg button.ok "OK")"
    if [[ -n "${MORDRED_INSTALL_LOG:-}" && -f "$MORDRED_INSTALL_LOG" ]]; then
      answer="$(dialog "$text" "$show" "$ok")"
      [[ "$answer" != "$show" ]] || open -a Console "$MORDRED_INSTALL_LOG" >/dev/null 2>&1 || true
    else
      dialog "$text" "$ok" >/dev/null || true
    fi
  fi
  exit 1
}

# A macOS dialog (the Mac installer has no terminal). The text goes in as an
# argument, never into the script. Prints the button pressed; empty when the
# dialog was dismissed or timed out.
# A notification while the installer keeps running (the Mac installer only).
notify() {
  [[ "$DIALOGS" == 1 ]] || return 0
  osascript - "$1" <<'EOF' >/dev/null 2>&1 || true
on run argv
  display notification (item 1 of argv) with title "Mordred"
end run
EOF
}

dialog() {
  local text="$1"
  shift
  osascript - "$text" "$@" <<'EOF' 2>/dev/null || true
on run argv
  set theButtons to items 2 thru -1 of argv
  try
    set answer to display dialog (item 1 of argv) buttons theButtons default button (item -1 of theButtons) with title "Mordred" giving up after 1800
    return button returned of answer
  on error
    return ""
  end try
end run
EOF
}

