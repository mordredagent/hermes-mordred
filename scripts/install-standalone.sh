readonly SMALL_MODEL_REVISION="1c6cbae21f8c38830ce337972b46fdae7b18eaaa"
readonly LARGE_MODEL_REPO="prism-ml/Ternary-Bonsai-2-27B-mlx-2bit"
readonly LARGE_MODEL_REVISION="24b5937a4a104a44f790b6ccbd0c79b6fabd4299"
